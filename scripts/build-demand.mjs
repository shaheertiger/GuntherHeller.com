#!/usr/bin/env node
/**
 * Search demand → data/demand.json
 *
 *   node scripts/build-demand.mjs [research/competitors/*.csv]
 *
 * Reads Semrush "Organic Positions" exports of sites that already rank for food nutrition searches
 * (EatBetter, CalorieKing, MyNetDiary; kept in research/, which is git-ignored) and maps every keyword
 * to the one food page on this site that best answers it. The result decides:
 *   - which /calories/ pages are indexable (the rest stay built and linked, but noindex and out of the sitemaps),
 *   - the search phrase a page is titled with ("93/7 ground beef" instead of USDA's record name).
 *
 * Only keywords and their US monthly search volumes are kept. Competitor URLs, positions and traffic are not.
 */
import fs from "node:fs";
import path from "node:path";
import { CHAINS } from "./chains.mjs";
import { ROOT, loadKeywords, INTENT, ASK, tok, core, makeMatcher } from "./keywords.mjs";

const { vol, files } = loadKeywords(process.argv.slice(2));

/** Restaurant chains: a query that is only the chain's name belongs on its hub page, not on one menu item. */
const chainOnly = new Map(CHAINS.map((c) => [tok(c.name).filter((w) => !ASK.has(w)).join(" "), c.slug]));

/* ---------------------------------------------------------------- foods (USDA records + imported store-brand products) */
const FOODS = [
  ...JSON.parse(fs.readFileSync(path.join(ROOT, "data/nutrition.json"), "utf8")).foods,
  ...(fs.existsSync(path.join(ROOT, "data/branded.json")) ? JSON.parse(fs.readFileSync(path.join(ROOT, "data/branded.json"), "utf8")).foods : []),
];
const { bestLoose } = makeMatcher(FOODS);

const demand = new Map(); // slug → { v, q: [query, volume][] }
const chainDemand = new Map(); // chain slug → volume
const gaps = new Map(); // unmatched core → volume
let matched = 0, total = 0;
for (const [k, v] of vol) {
  const intent = INTENT.test(k);
  const w = intent ? v : Math.round(v * 0.25); // bare food names ("schnitzel") are weaker nutrition demand
  const { t: q, text } = core(k);
  if (!q.length || q.length > 7) continue;
  total += w;
  const chain = chainOnly.get(q.join(" "));
  if (chain) { chainDemand.set(chain, (chainDemand.get(chain) ?? 0) + w); matched += w; continue; }
  const m = bestLoose(q);
  if (!m) { gaps.set(text, (gaps.get(text) ?? 0) + w); continue; }
  matched += w;
  const f = m.food;
  const e = demand.get(f.slug) ?? demand.set(f.slug, { v: 0, q: [] }).get(f.slug);
  e.v += w;
  if (intent) e.q.push([text, v]);
}

/* ---------------------------------------------------------------- output */
const out = {};
for (const [slug, e] of [...demand].sort((a, b) => b[1].v - a[1].v)) {
  // The search phrase most people use for this food: the core with the most volume across its keywords.
  const byCore = new Map();
  for (const [c, v] of e.q) byCore.set(c, (byCore.get(c) ?? 0) + v);
  const phrase = [...byCore].sort((a, b) => b[1] - a[1])[0]?.[0] ?? null;
  out[slug] = { v: e.v, phrase };
}
fs.writeFileSync(path.join(ROOT, "data/demand.json"), JSON.stringify({
  generated: new Date().toISOString().slice(0, 10),
  note: "Monthly US search volume of competitor-ranking keywords mapped to each food page (scripts/build-demand.mjs). phrase = the food as people search for it.",
  foods: out,
  chains: Object.fromEntries([...chainDemand].sort((a, b) => b[1] - a[1])),
}, null, 0).replace(/},"/g, '},\n"'));
const gapList = [...gaps].sort((a, b) => b[1] - a[1]).slice(0, 300);
fs.writeFileSync(path.join(ROOT, "seo/demand-gaps.md"),
  `# Searched foods with no page yet\n\nGenerated by \`scripts/build-demand.mjs\` on ${new Date().toISOString().slice(0, 10)}. ` +
  `Each line is a food people search nutrition for (monthly US volume) that no page on the site matches. Use it to pick what to add next.\n\n` +
  gapList.map(([c, v]) => `- ${c}: ${v.toLocaleString("en-US")}`).join("\n") + "\n");
const pages = Object.keys(out).length;
console.log(`build-demand: ${vol.size} keywords from ${files.length} files; ${Math.round((100 * matched) / total)}% of volume matched to ${pages} food pages; top gaps in seo/demand-gaps.md`);
